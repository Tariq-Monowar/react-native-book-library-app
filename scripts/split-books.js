/*
 * Splits each book in database/sherlock-holmes1|2 into one small module per
 * chapter, plus an index with only the chapter names. The app then loads
 * just the chapter being read (tens of KB) instead of the whole book (up to
 * 1.5 MB of text), which keeps memory low.
 *
 * Run after editing any book text:   node scripts/split-books.js
 */
const path = require('path');
const fs = require('fs');

const root = path.join(__dirname, '..');
require(path.join(root, 'node_modules/@babel/register'))({
  presets: [path.join(root, 'node_modules/@babel/preset-env')],
  only: [file => file.includes('/database/sherlock-holmes')],
});

// App book id -> source file (same mapping the app used before).
const BOOKS = {
  1: 'sherlock-holmes2/1.TheAdventuresofSherlockHolmes',
  2: 'sherlock-holmes2/2.TheMemoriesOfSherlockHolms',
  3: 'sherlock-holmes2/3.TheReturnOfSherlockHolmes',
  4: 'sherlock-holmes2/4.HisLastBao',
  5: 'sherlock-holmes2/5.CaseBookOfSherlockHolmes',
  6: 'sherlock-holmes1/4.TheValleyOfFear',
  7: 'sherlock-holmes1/3.TheHoundOfTheBaskervilles',
  8: 'sherlock-holmes1/2.TheSignOfTheFour',
  9: 'sherlock-holmes1/1.AStudyInScarlet',
};

const outDir = path.join(root, 'database/chapters');
fs.rmSync(outDir, {recursive: true, force: true});
fs.mkdirSync(outDir, {recursive: true});

const index = {};
const loaderLines = [];
let total = 0;

for (const [bookId, file] of Object.entries(BOOKS)) {
  const mod = require(path.join(root, 'database', file));
  const book = Object.values(mod)[0];
  const [meta, chapters] = book;
  const bookDir = path.join(outDir, `b${bookId}`);
  fs.mkdirSync(bookDir);
  const list = [];
  const loaders = [];
  for (const chapter of chapters) {
    const {desciption, ...rest} = chapter;
    list.push(rest);
    const body = `// Generated by scripts/split-books.js. Do not edit.\nmodule.exports = ${JSON.stringify(desciption ?? [])};\n`;
    fs.writeFileSync(path.join(bookDir, `c${chapter.id}.js`), body);
    total += body.length;
    loaders.push(`    ${chapter.id}: () => require('./b${bookId}/c${chapter.id}'),`);
  }
  index[bookId] = [meta, list];
  loaderLines.push(`  ${bookId}: {\n${loaders.join('\n')}\n  },`);
}

fs.writeFileSync(
  path.join(outDir, 'index.js'),
  `// Generated by scripts/split-books.js. Do not edit.\n// Book id -> [book names, chapters without their text].\nmodule.exports = ${JSON.stringify(index)};\n`,
);
fs.writeFileSync(
  path.join(outDir, 'loaders.js'),
  `// Generated by scripts/split-books.js. Do not edit.\n// Book id -> chapter id -> loads that chapter's text.\nmodule.exports = {\n${loaderLines.join('\n')}\n};\n`,
);
console.log(`Wrote ${Object.keys(BOOKS).length} books, ${loaderLines.length} loader groups, ${(total / 1e6).toFixed(1)} MB of chapter text.`);
