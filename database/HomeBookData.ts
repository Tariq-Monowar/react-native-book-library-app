// Book text lives in database/chapters, one small module per chapter
// (generated by scripts/split-books.js from the books in sherlock-holmes1/2).
// Opening a book loads only its chapter names; opening a chapter loads only
// that chapter's text. This keeps memory low however many books are read.
const chapterIndex: {
  [bookId: string]: [any, any[]];
} = require('./chapters/index');
const chapterLoaders: {
  [bookId: string]: {[chapterId: string]: () => any};
} = require('./chapters/loaders');

// [book names, chapters] for a book, without any chapter text.
export const getBookInternalData = (
  id: number,
): {id: number; data: any} | undefined => {
  const data = chapterIndex[String(id)];
  return data ? {id, data} : undefined;
};

// The text of one chapter: a list of {title, desc} sections.
export const getChapterText = (
  bookId: number,
  chapterId: number,
): {title: string; desc: string}[] => {
  const load = chapterLoaders[String(bookId)]?.[String(chapterId)];
  return load ? load() : [];
};
